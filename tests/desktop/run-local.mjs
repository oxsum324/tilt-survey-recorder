import {VERSION} from '../../model.js';
import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import {spawn, execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {executionOrigin} from '../execution-origin.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(root, '../..');
const git = (...args) => execFileSync('git', args, {cwd: repo, encoding: 'utf8'}).trim();
const head = git('rev-parse', 'HEAD');
assert.equal(git('status', '--porcelain'), '', 'Test a committed, clean source tree');
const sourceSnapshot = async () => {
  const files = git('ls-files', '-z').split('\0').filter(Boolean);
  return Object.fromEntries(await Promise.all(files.map(async file => [file,
    createHash('sha256').update(await fs.readFile(path.join(repo, file))).digest('hex')])));
};
const sourceBefore = await sourceSnapshot();
const outputRoot = path.resolve(process.env.TILT_DESKTOP_OUTPUT_ROOT || path.join(repo, 'output/desktop'));
const run = process.argv[2] || new Date().toISOString().replace(/[:.]/g, '-');
assert.match(run, /^[A-Za-z0-9_-]+$/, 'Use a simple, unique run name');
await fs.mkdir(outputRoot, {recursive: true});
const runDir = path.join(outputRoot, run);
await fs.mkdir(runDir); // EEXIST deliberately preserves every prior attempt.
const out = path.join(runDir, 'matrix');
await fs.mkdir(out);
const site = path.join(repo, '_site');
const manifest = JSON.parse(await fs.readFile(path.join(site, 'deploy-manifest.json'), 'utf8'));
assert.equal(manifest.commit, head, 'Build _site from this exact commit first');
for (const {path: file, sha256: expected} of manifest.files) {
  assert.equal(createHash('sha256').update(await fs.readFile(path.join(site, file))).digest('hex'), expected,
    `Staged file digest: ${file}`);
}
const types = {'.html': 'text/html;charset=utf-8', '.js': 'text/javascript;charset=utf-8',
  '.css': 'text/css;charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png',
  '.webmanifest': 'application/manifest+json'};
const server = http.createServer(async (req, res) => {
  try {
    const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    const file = path.resolve(site, '.' + (pathname === '/' ? '/index.html' : pathname));
    if (!file.startsWith(site + path.sep)) throw Error('Outside staged site');
    const bytes = await fs.readFile(file);
    res.writeHead(200, {'Content-Type': types[path.extname(file)] || 'application/octet-stream',
      'Cache-Control': 'no-store'});
    res.end(bytes);
  } catch {
    res.writeHead(404);
    res.end();
  }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const url = `http://127.0.0.1:${server.address().port}/?release=${VERSION}`;
const python = process.env.TILT_TEST_PYTHON || 'python';
const env = {...process.env, TILT_TEST_URL: url, TILT_TEST_HEAD: head,
  TILT_DESKTOP_RUN_DIR: runDir, TILT_DESKTOP_EVIDENCE_DIR: out,
  PYTHONIOENCODING: 'utf-8', PYTHONDONTWRITEBYTECODE: '1'};
// Label mutations use the PDF generated by this run, with no dependency on an old archive.
const commands = [
  ['diagnostics', process.execPath, [path.join(root, 'diagnostic-selftest.mjs')]],
  ['visibility', process.execPath, [path.join(root, 'visibility-selftest.mjs')]],
  ['matrix', process.execPath, [path.join(root, 'desktop-tests.mjs')]],
  ['pdf-labels', python, [path.join(root, 'pdf-label-selftest.py'),
    path.join(out, 'chrome-1280-normal/print-preview.pdf')]],
];
const receipt = {head, branch: git('branch', '--show-current'), url,
  ...executionOrigin(), targetScope: 'staged branch only; not a live-site deployment verification',
  startedUtc: new Date().toISOString(), node: process.version, python,
  sourceBefore, executions: []};
const save = () => fs.writeFile(path.join(runDir, 'execution.json'), JSON.stringify(receipt, null, 2));
console.log(`Desktop evidence: ${runDir}`);
try {
  await save();
  for (const [name, executable, args] of commands) {
    const startedUtc = new Date().toISOString(), chunks = [];
    const child = spawn(executable, args, {cwd: repo, env, stdio: ['ignore', 'pipe', 'pipe']});
    for (const stream of [child.stdout, child.stderr]) stream.on('data', data => {
      chunks.push(data); process.stdout.write(data);
    });
    const completion = await new Promise(resolve => {
      child.on('error', error => resolve({exitCode: 1, error: error.message}));
      child.on('exit', (code, signal) => resolve({exitCode: code ?? 1, signal}));
    });
    await fs.writeFile(path.join(runDir, `${name}.log`), Buffer.concat(chunks));
    receipt.executions.push({name, command: [executable, ...args], startedUtc,
      endedUtc: new Date().toISOString(), ...completion});
    await save();
    if (completion.exitCode !== 0) {
      process.exitCode = completion.exitCode;
      break;
    }
  }
} finally {
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
  receipt.sourceAfter = await sourceSnapshot();
  receipt.headAfter = git('rev-parse', 'HEAD');
  receipt.statusAfter = git('status', '--porcelain');
  receipt.endedUtc = new Date().toISOString();
  await save();
  const files = [];
  const collect = async dir => {
    for (const item of await fs.readdir(dir, {withFileTypes: true})) {
      const file = path.join(dir, item.name);
      if (item.isDirectory()) await collect(file);
      else {
        const bytes = await fs.readFile(file);
        files.push({file: path.relative(runDir, file).replaceAll(path.sep, '/'),
          sha256: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length});
      }
    }
  };
  await collect(runDir);
  await fs.writeFile(path.join(runDir, 'evidence-sha256.json'), JSON.stringify(files, null, 2));
  assert.equal(receipt.headAfter, head, 'HEAD must remain unchanged during tests');
  assert.equal(receipt.statusAfter, '', 'Tests must leave the source tree clean');
  assert.deepEqual(receipt.sourceAfter, sourceBefore, 'Tracked source must remain unchanged');
}
